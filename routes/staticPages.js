// Toggle page status
router.patch('/:id/toggle-status', async (req, res) => {
  try {
    const { id } = req.params;
    
    console.log('📄 Toggling status for static page:', id);
    
    const page = await StaticPage.findOne({ id: parseInt(id) });
    
    if (!page) {
      return res.status(404).json({ error: 'Static page not found' });
    }
    
    page.isActive = !page.isActive;
    const updatedPage = await page.save();
    
    console.log('✅ Static page status toggled successfully:', id);
    
    res.json(updatedPage);
  } catch (error) {
    console.error('❌ Error toggling static page status:', error);
    res.status(500).json({ 
      error: 'Internal server error',
      message: error.message 
    });
  }
});

